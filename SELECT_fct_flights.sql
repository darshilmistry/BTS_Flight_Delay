SELECT 
    CAST(FlightDate AS DATE) AS FlightDate,
    CAST(DOT_ID_Reporting_Airline AS INT) AS DOT_ID_Reporting_Airline,
    CAST(Tail_Number AS VARCHAR(7)) AS Tail_Number,
    CAST(Flight_Number_Reporting_Airline AS INT) AS Flight_Number_Reporting_Airline,
    CAST(OriginAirportID AS INT) AS OriginAirportID,
    CAST(Cancelled AS TINYINT) AS Cancelled,
    CAST(CRSDepTime AS VARCHAR(5)) AS CRSDepTime,
    CAST(DepDelay AS SMALLINT) AS DepDelay,
    CAST(TaxiOut AS SMALLINT) AS TaxiOut,
    CAST(WheelsOff AS VARCHAR(5)) AS WheelsOff,
    CAST(DestAirportID AS INT) AS DestAirportID,
    CAST(CRSArrTime AS VARCHAR(5)) AS CRSArrTime,
    CAST(ArrDelay AS SMALLINT) AS ArrDelay,
    CAST(WheelsOn AS VARCHAR(5)) AS WheelsOn,
    CAST(TaxiIn AS SMALLINT) AS TaxiIn,
    CAST(Distance AS SMALLINT) AS Distance,
    CAST(Diverted AS TINYINT) AS Diverted,
    CAST(CRSElapsedTime AS SMALLINT) AS CRSElapsedTime,
    CAST(ActualElapsedTime AS SMALLINT) AS ActualElapsedTime,
    CAST(AirTime AS SMALLINT) AS AirTime,
    CAST(CarrierDelay AS VARCHAR(10)) AS CarrierDelay,
    CAST(WeatherDelay AS VARCHAR(10)) AS WeatherDelay,
    CAST(NASDelay AS VARCHAR(10)) AS NASDelay,
    CAST(SecurityDelay AS VARCHAR(10)) AS SecurityDelay,
    CAST(LateAircraftDelay AS VARCHAR(10)) AS LateAircraftDelay,
    CAST(DivArrDelay AS VARCHAR(10)) AS DivArrDelay,
    CAST(TotalAddGTime AS VARCHAR(10)) AS TotalAddGTime,
    CAST(LongestAddGTime AS VARCHAR(10)) AS LongestAddGTime,
    CAST(DivAirportLandings AS VARCHAR(10)) AS DivAirportLandings,
    CAST(DivReachedDest AS VARCHAR(10)) AS DivReachedDest,
    CAST(DivActualElapsedTime AS VARCHAR(10)) AS DivActualElapsedTime,
    CAST(DivDistance AS VARCHAR(10)) AS DivDistance
FROM staging.raw_flights;
